/**
 * Turn any pattern name + optional classical note/description into a clear everyday Chinese explanation.
 */
export function explainPatternPlain(name: string, description = '', note = ''): string {
  if (PATTERN_PLAIN[name]) {
    return PATTERN_PLAIN[name];
  }

  // Dynamic patterns from patterns.ts:
  // 1) `${star}化禄入命`
  const luMingMatch = /^(.+?)化禄入命$/.exec(name);
  if (luMingMatch) {
    const star = luMingMatch[1];
    const hint = DYNAMIC_STAR_HINT[star] || `发挥「${star}」自带的天赋优势`;
    return `大白话：你天生自带一股把生活过顺的甜头和好人缘。在工作与赚钱上尤其擅长「${hint}」，比起死磕硬磨，顺着自己最拿手的方式做事反而更容易看到实在回报。`;
  }

  // 2) `${star}化忌入命` / `${star}化忌入迁`
  const jiMatch = /^(.+?)化忌入(命|迁)$/.exec(name);
  if (jiMatch) {
    const [, star, where] = jiMatch;
    return where === '命'
      ? `大白话：你最容易跟自己较劲、把事全往心上揽。尤其遇到「${star}」代表的领域或情绪触发点时，越在乎就越放不下、反复钻牛角尖。其实把标准稍微松一半、学会向信得过的人倾诉分担，很多内耗当场就能少一半。`
      : `大白话：你自己心里常觉得平静还好，可一出门跟外人打交道、换新环境或跑异地项目，就特别容易遇到「沟通误会、节奏被打乱或被陌生人挑刺」（与「${star}」的特质有关）。对策是重要合作提前留足余地并白纸黑字写清楚，别跟陌生人或路人情绪硬刚。`;
  }

  // Try matching stripped suffix / partial key
  const stripped = name.replace(/（.*?）/g, '').trim();
  if (PATTERN_PLAIN[stripped]) {
    return PATTERN_PLAIN[stripped];
  }

  // Structured fallback translating common classical Ming pattern phrasing
  const combined = [note, description].filter(Boolean).join('；');
  if (!combined) {
    return `这是传统古籍总结的一类星曜结构组合，阅读时重点看本宫与三方是否配合得力、有没有吉星搭把手。`;
  }

  return explainClassicExcerpt(combined, name, 'quanshu').plain;
}

/**
 * Translate harsh/archaic classical marriage phrases (heming-knowledge) into calm modern guidance.
 */
export function explainMarriageClassical(raw: string, label = ''): string {
  const hits: string[] = [];
  for (const [pattern, text] of MARRIAGE_ARCHAIC_MAP) {
    if (pattern.test(raw)) {
      hits.push(text);
    }
  }
  if (hits.length > 0) {
    return hits.join(' ');
  }

  // General classical-tone softer translation for any remaining STAR_IN_FUQI_GU / SIHUA_IN_FUQI_GU note
  const plain = explainClassicExcerpt(raw, label ? `婚姻口诀·${label}` : '婚姻口诀', 'quanshu').plain;
  return plain;
}

/**
 * Translate a snippet from 《紫微斗数全书》 or 《天纪》 + extract inline gloss pills for terms present.
 */
export function explainClassicExcerpt(
  text: string,
  section = '',
  sourceKind: 'quanshu' | 'tianji' = 'quanshu',
): ClassicExcerptPlain {
  const cleanText = text.replace(/\s+/g, ' ').trim();
  const terms: ClassicTermGloss[] = [];
  for (const [re, term, gloss] of CORE_TERM_GLOSS) {
    if (re.test(cleanText) && terms.length < 6) {
      terms.push({ term, gloss });
    }
  }

  // Extract section intro
  let intro = '';
  for (const [re, desc] of QUANSHU_SECTION_INTRO) {
    if (re.test(section)) {
      intro = desc;
      break;
    }
  }

  // Extract stars & key classical cues present in text
  const stars = [
    '紫微', '天机', '太阳', '武曲', '天同', '廉贞', '天府', '太阴', '贪狼', '巨门', '天相', '天梁', '七杀', '破军',
    '左辅', '右弼', '文昌', '文曲', '天魁', '天钺', '禄存', '天马', '擎羊', '陀罗', '火星', '铃星', '地空', '地劫', '天刑', '天姚', '红鸾', '天喜',
  ].filter((s) => cleanText.includes(s));

  const palaceMentions = [
    '命宫', '身宫', '兄弟', '夫妻', '妻妾', '子女', '财帛', '疾厄', '迁移', '仆役', '奴仆', '官禄', '田宅', '福德', '父母',
  ].filter((p) => cleanText.includes(p));

  const cues: string[] = [];

  if (/夹/.test(cleanText)) {
    cues.push('这里提到了“夹”——意思是左右邻宫两边的星曜贴着影响中间宫位');
  }
  if (/拱|朝垣|加会|同度|同宫|守命|守身/.test(cleanText)) {
    cues.push('谈的是几颗星曜合在一起或互相呼应时产生的叠加效果');
  }
  if (/庙|旺|得地/.test(cleanText)) {
    cues.push('强调落在了舒展得力的位置，星曜的正向优点比较容易自然发挥');
  }
  if (/陷|失陷|反背|空亡/.test(cleanText)) {
    cues.push('提示落在不够顺手的位置或遇上消耗，往往要先磨练调整、避免凭一时冲动拍板');
  }
  if (/四杀|羊陀|火铃|擎羊|陀罗|火星|铃星|空劫/.test(cleanText)) {
    cues.push('提醒注意煞星带来的急性冲动、拉扯拖延或意外损耗，重在提前设好风控缓冲');
  }
  if (/大限|二限|流年|太岁|运|墓/.test(cleanText)) {
    cues.push('重点看不同十年阶段（大限）或流年时机走到了哪一关，不能只靠原盘死板定论');
  }
  if (/克|孤|贫|贱|凶|夭|刑|伤|死|埋尸|水厄|破/.test(cleanText)) {
    cues.push('注意古书喜用极重字眼警示“高压力、高冲突或高波动领域”，现代解读只看成需要注意沟通边界、健康作息或风险控管的提醒，绝非不可改变的宿命');
  } else if (/富|贵|荣|昌|吉|寿|福|双禄|三奇/.test(cleanText)) {
    cues.push('整体偏正向肯定：当配套的吉星或助力凑齐时，人生资源、口碑或收获往往相对丰厚');
  }
  if (/先贫后富|少年不遂|四十后|晚|大器/.test(cleanText)) {
    cues.push('带有明显“先难后顺、中后期积累起来”的时间节奏感');
  }
  if (/阴骘|心念|改命|修养|德|地|阳宅|人/.test(cleanText)) {
    cues.push('强调后天自身心态、做人德行与主动选环境/选风控的重要性大于死盯先天纸面符号');
  }

  // Build readable concise summary paragraph
  const parts: string[] = [];
  if (intro && !section.startsWith('婚姻口诀')) {
    parts.push(intro);
  }

  if (sourceKind === 'tianji') {
    parts.push(
      stars.length
        ? `这段《天纪》口述核心是在拆解「${stars.slice(0, 4).join('、')}」${
            palaceMentions.length ? `和${palaceMentions.slice(0, 2).join('、')}相关时` : ''
          }的实操规律：`
        : `这段《天纪》教学的核心想法用白话来讲：`,
    );
  } else {
    parts.push(
      stars.length
        ? `这段口诀主要针对「${stars.slice(0, 4).join('、')}」${
            palaceMentions.length ? `（涉及${palaceMentions.slice(0, 3).join('、')}）` : ''
          }来论：`
        : palaceMentions.length
        ? `这段古籍重点围绕「${palaceMentions.slice(0, 3).join('、')}」的生活领域来看：`
        : `这段古籍文字如果翻译成日常好懂的意思，大致可以这样理解：`,
    );
  }

  if (cues.length > 0) {
    parts.push(`${cues.join('；')}。`);
  } else {
    parts.push(
      sourceKind === 'tianji'
        ? '重点在于提醒看盘不能只抓死板单条，要结合人的选择、环境与大限时机整体去平衡。'
        : '主要提醒在特定宫位与时期里，顺势用好自身优势、提前避开性格短板或冲动陷阱。',
    );
  }

  return {
    plain: [
      intro && !section.startsWith('婚姻口诀') ? intro : '',
      (() => {
        for (const [re, versePlain] of FAMOUS_VERSE_PLAIN) {
          if (re.test(cleanText)) return `【白话直解】${versePlain}`;
        }
        return '';
      })(),
      parts.slice(intro && !section.startsWith('婚姻口诀') ? 1 : 0).join(' '),
    ]
      .filter(Boolean)
      .join(' '),
    terms,
  };
}

