function auxPriority(name: string): number {
  if (CORE_LUCKY_STARS.has(name)) return 0;
  if (CORE_SHA_STARS.has(name)) return 1;
  if (CORE_TREASURE_STARS.has(name)) return 2;
  if (ROMANCE_LUCKY_STARS.has(name) || MINOR_SHA_WATCH.has(name)) return 3;
  return 4;
}

export function summarizePalaceExtras(
  starNames: string[],
  shier?: { boshi: string; suiqian: string; jiangqian: string },
  selfSiHua?: { siHua: SiHua; starName: string }[],
): string {
  const parts: string[] = [];
  const auxHits = [...starNames]
    .filter((n) => AUX_STAR_PLAIN[n])
    .sort((a, b) => auxPriority(a) - auxPriority(b))
    .slice(0, 6)
    .map((n) => `「${n}」${AUX_STAR_PLAIN[n]}`);
  if (auxHits.length) {
    parts.push(`同宫辅煞点睛：${auxHits.join(' ')}`);
  }

  if (selfSiHua && selfSiHua.length > 0) {
    const shText = selfSiHua
      .map(
        (m) =>
          `${m.starName}在本宫自化${m.siHua}（表示这个宫位自身容易主动产生与「${
            m.siHua === '禄'
              ? '顺势投入与分享'
              : m.siHua === '权'
              ? '强势自主争夺主导'
              : m.siHua === '科'
              ? '主动看重口碑与解释梳理'
              : '反复自我消耗或越抓越容易变数流失'
          }」相关的内生变化）`,
      )
      .join('；');
    parts.push(`宫干自化：${shText}。`);
  }

  if (shier) {
    const sNotes = [shier.boshi, shier.suiqian, shier.jiangqian]
      .filter((name, idx, arr) => arr.indexOf(name) === idx && SHIER_SHEN_PLAIN[name])
      .slice(0, 3)
      .map((name) => `${name}（${SHIER_SHEN_PLAIN[name]}）`);
    if (sNotes.length) {
      parts.push(`十二神参考：${sNotes.join('；')}。`);
    }
  }

  return parts.join('\n') || '本宫其余杂曜偏温和，主要以主星与三方四正的整体联动为主。';
}
