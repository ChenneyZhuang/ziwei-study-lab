export function findDoubleStarCombo(names: string[]): string | undefined {
  if (names.length < 2) return undefined;
  for (let i = 0; i < names.length; i++) {
    for (let j = i + 1; j < names.length; j++) {
      const k1 = `${names[i]}+${names[j]}`;
      const k2 = `${names[j]}+${names[i]}`;
      if (DOUBLE_COMBO_RAW[k1]) return DOUBLE_COMBO_RAW[k1];
      if (DOUBLE_COMBO_RAW[k2]) return DOUBLE_COMBO_RAW[k2];
    }
  }
  return undefined;
}

