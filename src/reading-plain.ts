function isWeakBrightness(b?: string): boolean {
  return b === '陷' || b === '不' || b === '闲' || b === '地';
}

export function buildPalacePlainSynthesis(params: {
  palaceKey: PalaceKey;
  observedNames?: string[];
  observedStars?: { name: string; brightnessRaw?: string }[];
  borrowed: boolean;
  strongCount: number;
  weakCount: number;
  siHuas: { starName: string; siHua: SiHua }[];
  luckyNames: string[];
  shaNames: string[];
  decadeInfo?: { ageRange: string; palaceName: string; matchesThisPalace: boolean };
  yearlyBranchInfo?: { year: number; palaceName: string; matchesThisPalace: boolean };
}): PlainSynthesisResult {
  const {
    palaceKey,
    observedNames: legacyNames,
    observedStars: rawStars,
    borrowed,
    strongCount,
    weakCount,
    siHuas,
    luckyNames,
    shaNames,
    decadeInfo,
    yearlyBranchInfo,
  } = params;

  const stars: { name: string; brightnessRaw?: string }[] =
    rawStars ?? (legacyNames ?? []).map((name) => ({ name }));
  const names = stars.map((s) => s.name);
  const firstStar = stars[0];
  const secondStar = stars[1];

  const primary = firstStar ? STAR_PLAIN_PROFILES[firstStar.name]?.palaces[palaceKey] : undefined;
  const secondary = secondStar ? STAR_PLAIN_PROFILES[secondStar.name]?.palaces[palaceKey] : undefined;

  const coreSha = shaNames.filter((n) => CORE_SHA_STARS.has(n));
  const minorWatch = shaNames.filter((n) => MINOR_SHA_WATCH.has(n));
  const coreLucky = luckyNames.filter((n) => CORE_LUCKY_STARS.has(n));
  const coreTreasure = luckyNames.filter((n) => CORE_TREASURE_STARS.has(n));
  const romanceLucky = luckyNames.filter((n) => ROMANCE_LUCKY_STARS.has(n));
  const hasJiStar = siHuas.some((s) => s.siHua === '忌');

  const doubleTitle = findDoublePlainTitle(names);
  const plainTitle = primary
    ? doubleTitle && palaceKey === '命宫'
      ? doubleTitle
      : primary.title
    : '随身边环境和同路人变化而塑造的新舞台';

  const baseQuote = primary
    ? doubleTitle && palaceKey === '命宫'
      ? secondary
        ? `${primary.quote} 同时你也兼有“${secondary.quote.replace(/[。！]$/, '')}”的另一面。`
        : primary.quote
      : doubleTitle
      ? `${doubleTitle}——${primary.quote}`
      : secondary
      ? `${primary.quote} 同时你也兼有另一面的细腻弹性，两边性格都会在不同阶段显出来。`
      : primary.quote
    : '这一块对你来说像一张高度灵活的白纸，挑对环境与靠谱同行人比自己单打独斗更决定成败。';

  const firstIsWeak = Boolean(firstStar && isWeakBrightness(firstStar.brightnessRaw));
  const needsBalanceCaveat = primary && (firstIsWeak || coreSha.length > 0 || hasJiStar);
  const plainQuote = needsBalanceCaveat
    ? `${baseQuote.replace(/[。！]$/, '')}；过程中起伏打磨或心里较真绷紧的地方会多几分，提前写明规则并慢半拍拿决定就稳得多。`
    : baseQuote;

  const resolveLifeText = (
    starName: string,
    brightnessRaw: string | undefined,
    entry: { life: string; weakLife?: string },
  ): string => {
    if (isWeakBrightness(brightnessRaw)) {
      return entry.weakLife || WEAK_STAR_PALACE_PLAIN[starName]?.[palaceKey] || `${entry.life} 只是起步期顺手支撑相对少一点，需要花比别人多两分耐心慢慢积累磨合后才会真正出彩。`;
    }
    return entry.life;
  };

  const lifeLines: string[] = [];
  if (primary && firstStar) {
    lifeLines.push(resolveLifeText(firstStar.name, firstStar.brightnessRaw, primary));
  } else {
    lifeLines.push(
      '这一块没有特别固定写死的性格剧本，你在这方面的状态极易受到周围环境气氛、身边亲近搭档以及当前人生阶段的影响——遇到稳妥有格局的人与平台，你就会迅速跟着立稳做大。',
    );
  }

  if (borrowed && primary) {
    lifeLines.push(
      '你在这一块的风格很有弹性，平时不一定时刻显露，往往遇到外部事情推动或身边人的带动时才明显展现出来，选对身边同行的伙伴格外关键。',
    );
  }

  if (secondary && secondStar) {
    const secText = resolveLifeText(secondStar.name, secondStar.brightnessRaw, secondary);
    lifeLines.push(`与此同时，你身上还有另一重特质：${secText}`);
  }

  // Reconciled SiHua plain modifiers (preventing 禄+忌 / 权+忌 / 科+忌 contradiction, with star specificity)
  const hasLu = siHuas.some((s) => s.siHua === '禄');
  const hasQuan = siHuas.some((s) => s.siHua === '权');
  const hasKe = siHuas.some((s) => s.siHua === '科');
  const hasJi = hasJiStar;

  if (hasLu && hasJi) {
    lifeLines.push(
      '尤其值得留心的是，这方面同时带着「资源和投入感颇旺，但心里也最较真最容易因为细节生波折」的双重牵扯——往往一边看得到好机会和好心情，一边又因为太想抓紧不放而在规则或相处细节上起小卡顿；提前写明账目与界限，就能留住顺手的好收成。',
    );
  } else if (hasQuan && hasJi) {
    lifeLines.push(
      '还要特别留意，你在这一块想扛大旗做主的干劲和自我紧绷感拧在了一起——越想用力压住局面不出错，越容易与身边规矩或搭档顶牛生摩擦；学会抓大方向放小节，反而稳顺得多。',
    );
  } else {
    if (hasLu) {
      lifeLines.push('而且你在这上面带着天生的好感与舒畅缘分——不仅自己更愿意用心投入，做起来也相对顺手，容易看见正面回馈和好心情。');
    }
    if (hasQuan) {
      lifeLines.push('加上你在这块骨子里特别有掌控欲与不服输的干劲，不想被别人牵着鼻子走，越扛压力越想干出一番成绩。');
    }
    if (hasKe && hasJi) {
      lifeLines.push(
        '难得的是，虽然这方面你格外上心较真、容易自己跟自己紧绷打磨，好在同时有一股冷静讲理、能凭好名声和懂行贵人圆场化解的温和护佑，遇到卡壳终归找得到体面解法。',
      );
    } else if (hasKe) {
      lifeLines.push('值得加分的是，这方面天生带着一层口碑和冷静化解的福气——遇到难堪局面时，总能凭名声、体面讲道理或靠谱前辈提点顺利过渡。');
    } else if (hasJi) {
      lifeLines.push('同时这一块恰恰也是你最上心、最容易自己跟自己较劲的地方——越想紧紧抓住不出错，心里越容易紧绷起波折；放缓一点步调、把关键承诺先看清写明，反而省心很多。');
    }
  }

  for (const sh of siHuas) {
    const spec = STAR_SIHUA_SPECIFIC[`${sh.starName}化${sh.siHua}`];
    if (spec?.plain) {
      lifeLines.push(spec.plain);
    }
  }

  if (coreSha.length > 0) {
    const hasYangTuo = coreSha.some((n) => YANG_TUO_STARS.has(n));
    const hasHuoLing = coreSha.some((n) => HUO_LING_STARS.has(n));
    const hasKong = coreSha.some((n) => KONG_SHA_STARS.has(n));

    const shaByPalace: Partial<Record<PalaceKey, string>> = {
      命宫: '性格深处偶尔带点急脾气硬杠或者在一个小疙瘩上反复打转放不下的韧劲，重要选择放过一夜再拍板少走很多弯路。',
      财帛: hasKong
        ? '金钱方面容易因理想化判断或突发开支出现“看着有机会却忽然绕个弯漏掉”的情况，绝不拿家用老本盲目梭哈，分散稳存最有安全感。'
        : '钱财方面容易遇到计划外急花销、冲动开支或硬碰硬的利益摩擦，大笔进出和借贷担保先多核一遍账目最稳妥。',
      官禄: '职场推进中容易碰上流程突发大改、急活插队或团队摩擦磨合，越是想一拍桌子换赛道越要先把退路接稳。',
      夫妻: '两人相处磨合期讲话直接带刺或因为各有脾气憋着反复琢磨的小拌嘴多一点，多留半天冷静台阶很保护感情。',
      疾厄: '平时累过头或者心火上涌时容易用急性发炎、突发小伤磕碰、牙龈肿痛或睡眠被搅浅报警，运动出行稳一点别硬熬夜。',
      仆役: '外围往来的圈子里人品混杂，偶尔容易遇到临时变卦或爱暗自算计的人，合作共事守住规则分清账务绝不吃亏。',
    };

    if (shaByPalace[palaceKey]) {
      lifeLines.push(shaByPalace[palaceKey]!);
    } else if (hasKong && !hasYangTuo && !hasHuoLing) {
      lifeLines.push(
        '这块思维偏跳脱有创意，常不按世俗老套路出牌，不过现实推进时也容易遇到计划中途突然改道或期望落差，重大投入前多留一分备案最安心。',
      );
    } else if (hasHuoLing && !hasYangTuo) {
      lifeLines.push(
        '这方面行动力上来极快，但也偏容易碰到突发小变数或情绪突然急躁上火，大事等心情平复半小时再回复更顺畅。',
      );
    } else {
      lifeLines.push(
        '这块日常推进不会一直一帆风顺，中途偶尔会遇到正面摩擦碰撞或在一个卡点上反复磨炼几遍，啃过去之后功夫倒极其扎实。',
      );
    }
  } else if (minorWatch.length > 0) {
    if (minorWatch.includes('天刑') && (palaceKey === '官禄' || palaceKey === '命宫' || palaceKey === '财帛')) {
      lifeLines.push('你在这块天生多了一层极强的自律规矩与原则敏感度，干专业风控、合规或技术把关反而是加分护栏，日常对自己和旁人别太严苛就好。');
    } else if ((minorWatch.includes('孤辰') || minorWatch.includes('寡宿')) && (palaceKey === '夫妻' || palaceKey === '福德' || palaceKey === '命宫')) {
      lifeLines.push('关起门来你非常需要保留一块清静不被打扰的独立精神角落，别让在乎你的人误以为冷淡，偶尔主动把心里关怀说出口就很暖。');
    }
  }

  if (coreLucky.length > 0 && coreSha.length > 0) {
    lifeLines.push('好在虽然过程里难免有急躁波折或突发考验，你身边却并不缺靠谱同行者或前辈长者的顺手搭把手，遇到卡点开口借力比硬扛容易解局得多。');
  } else if (coreLucky.length > 0) {
    lifeLines.push('加上身边往往有讲理靠谱的同行搭档、规则助力或前辈贵人顺手托一把，遇到卡住的时候多向内行请教极容易打通。');
  } else if (coreTreasure.includes('禄存') && !coreSha.some((n) => KONG_SHA_STARS.has(n))) {
    lifeLines.push('而且你在这块天生带着一重懂得留后路、稳稳攒积累的保守防线，不轻易乱冒无把握的大险。');
  }

  if (coreTreasure.includes('天马') && (palaceKey === '迁移' || palaceKey === '财帛' || palaceKey === '官禄')) {
    lifeLines.push('而且这件事天生喜动不喜闷——多走动出差、跨区域跑业务或在快速迭代的流动性环境里反而越跑越生财有起色。');
  }

  if (romanceLucky.length > 0 && (palaceKey === '命宫' || palaceKey === '夫妻' || palaceKey === '迁移' || palaceKey === '仆役')) {
    lifeLines.push('同时你在人缘审美与情绪互动上自带亲和吸引与小喜气，只要守住清晰边界就是极佳的人脉好感加分。');
  }

  // Current Decade & Yearly overlay in pure plain language
  if (decadeInfo?.matchesThisPalace) {
    lifeLines.push(`尤其值得一提的是，你这整十年（${decadeInfo.ageRange}岁）的人生主轴正走在这一块上，现在每一步选择分量都很重，照稳妥方向踏实深耕最值。`);
  }
  if (yearlyBranchInfo?.matchesThisPalace) {
    lifeLines.push(`${yearlyBranchInfo.year}年这一年，这一块的事件特别容易被推到台前变成生活重点，适合优先把这一头理顺。`);
  }

  const adviceList: string[] = [];
  if (primary) adviceList.push(primary.advice);
  else adviceList.push('先把身边靠谱的共事圈和好环境选对，你的潜力会被稳稳托起来。');

  if (hasJi) {
    adviceList.push('面对你最在乎、最容易紧绷的这件事，切忌一时心急一口气拍板，慢一晚、写清楚再做决定。');
  }
  if (coreSha.length > 0 && palaceKey === '财帛') {
    adviceList.push('大额花钱和借贷投资尽量缓一缓，熟人开口借钱先想想自己能不能白送、不能就果断婉拒。');
  }

  const glossary: string[] = [];
  if (borrowed) {
    glossary.push('【无主星（空宫）】不是“这里什么都没有”，而是像一张更有可塑性、没有写死剧本的白纸，平时很大程度受对面环境与身边同伴性格带动。');
  }
  if (strongCount > 0 || weakCount > 0) {
    glossary.push('【庙旺 / 落陷（亮度）】就像同一盏灯处在白天还是黑夜：顺手省力的位置叫“庙旺”，需要自己多花一倍心思去磨合、慢慢攒经验成器的位置叫“落陷”，绝不直接等于好命或坏命。');
  }
  if (siHuas.length > 0) {
    glossary.push('【四化（禄 / 权 / 科 / 忌）】是命盘里用来放大某方面情绪和投入度的四个开关：「禄」代表顺畅与资源流入；「权」代表想做主拿结果；「科」代表好名声、考试和有办法圆场；「忌」代表你心弦绷得最紧、最执着也最容易反复琢磨之处。');
  }
  if (coreSha.length > 0) {
    glossary.push('【六煞星】代表带着冲击力、急脾气、执念反复或意外变化因素的提醒信号，在哪个领域出现，哪一块就越不能大意冒进、越需要先想好风控退路。');
  }

  return {
    plainTitle,
    plainQuote,
    plainSummary: lifeLines.join(' '),
    plainAdvice: adviceList.join(' '),
    glossary,
  };
}
